class DataConversion 
{

    public static void main(String[] args) {
        
        //conversion 

        int a = 10;
        double b = a;
         System.out.println(b);

        //Casting

        double c = 20;
        int d = (int)c;
        System.out.println(d);

        //type promotion 

        byte ae=12;
        byte be=20;

        int result= ae* be;

        System.out.println(result);


    }
}